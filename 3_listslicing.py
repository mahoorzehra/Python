#slicing            03/09/26
lt = ['wasiq', 'umer', 17, 19.6, 'khan', 900]
print(lt)

#to print range from a specific index to another specific index 
print(lt[1:4])

#to print backwards
print(lt[:-4])
print(lt[:-1 ])

# to print a range from beginning to a certain value
print(lt[:3])

# to print range from end to a specific value
print(lt[:-3])

# to print values with jumps
print(lt[::2])

#to print values from a specific range with jumps
print(lt[1:4:2])
